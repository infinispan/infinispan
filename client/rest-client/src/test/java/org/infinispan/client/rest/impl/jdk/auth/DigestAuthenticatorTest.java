package org.infinispan.client.rest.impl.jdk.auth;

import static java.util.concurrent.TimeUnit.SECONDS;
import static org.assertj.core.api.Assertions.assertThat;

import java.io.IOException;
import java.io.OutputStream;
import java.net.InetSocketAddress;
import java.nio.charset.StandardCharsets;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.security.SecureRandom;
import java.util.ArrayList;
import java.util.Collections;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.concurrent.CompletableFuture;
import java.util.concurrent.atomic.AtomicReference;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

import org.infinispan.client.rest.RestClient;
import org.infinispan.client.rest.RestResponse;
import org.infinispan.client.rest.configuration.RestClientConfigurationBuilder;
import org.infinispan.commons.util.Util;
import org.junit.jupiter.api.Test;

import com.sun.net.httpserver.HttpExchange;
import com.sun.net.httpserver.HttpServer;

/**
 * Verifies that the per-request digest nonce bookkeeping of {@link DigestAuthenticator} (nonce count, client
 * nonce, last seen nonce) is not shared between concurrent requests. The simulated server issues a fresh
 * nonce per request and verifies the digest response exactly as RFC 7235 requires, so any state shared
 * between requests or any corrupted digest computation is rejected.
 */
class DigestAuthenticatorTest {

   private static final String USERNAME = "user";
   private static final String PASSWORD = "pass";
   private static final String REALM = "TestRealm";
   private static final String URI = "/rest/v2/caches";
   private static final Pattern DIGEST_FIELD = Pattern.compile("([a-z]+)=(?:\"([^\"]*)\"|([^\s,]*))");

   @Test
   void concurrentRequestsComputeIndependentDigests() throws Exception {
      int numRequests = 20;
      CurrentNonceServer server = startCurrentNonceServer();
      try (RestClient client = createClient(server.httpServer)) {
         List<CompletableFuture<RestResponse>> futures = new ArrayList<>(numRequests);
         for (int i = 0; i < numRequests; i++) {
            futures.add(client.caches().toCompletableFuture());
         }
         CompletableFuture.allOf(futures.toArray(new CompletableFuture[0])).get(30, SECONDS);
         for (CompletableFuture<RestResponse> future : futures) {
            assertThat(future.get().status()).isEqualTo(RestResponse.OK);
         }
         // Every accepted digest must be the first attempt of its own request (nc=1) and carry the client
         // nonce generated by that very request: with state shared between requests, cnonces would be reused
         // and the nonce count would not start at 1 for every request.
         assertThat(server.acceptedCnonces).hasSize(numRequests);
         assertThat(server.acceptedCnonces).doesNotHaveDuplicates();
         assertThat(server.acceptedNcValues).containsOnly("00000001");
      } finally {
         server.stop();
      }
   }

   @Test
   void stalePreauthenticationRetriesWithFreshChallenge() throws Exception {
      CurrentNonceServer server = startCurrentNonceServer();
      try (RestClient client = createClient(server.httpServer)) {
         var first = client.caches().toCompletableFuture().get(30, SECONDS);
         assertThat(first.status()).isEqualTo(RestResponse.OK);
         // The second request is preauthenticated with the nonce cached by the first one; the server has since
         // rotated its nonce, so the request must recover from a fresh challenge.
         var second = client.caches().toCompletableFuture().get(30, SECONDS);
         assertThat(second.status()).isEqualTo(RestResponse.OK);
         assertThat(server.acceptedNonces).hasSize(2);
         assertThat(server.acceptedNonces.get(0)).isNotEqualTo(server.acceptedNonces.get(1));
         assertThat(server.acceptedNcValues).containsOnly("00000001");
      } finally {
         server.stop();
      }
   }

   @Test
   void retryWithSameNonceIncrementsNonceCount() throws Exception {
      StaleNonceServer server = startStaleNonceServer();
      try (RestClient client = createClient(server.httpServer)) {
         var response = client.caches().toCompletableFuture().get(30, SECONDS);
         assertThat(response.status()).isEqualTo(RestResponse.OK);
         // The server re-challenged with the same nonce and stale=true; the client must increment the nonce
         // count rather than restarting it.
         assertThat(server.acceptedNcValues).containsExactly("00000002");
      } finally {
         server.stop();
      }
   }

   private static CurrentNonceServer startCurrentNonceServer() throws IOException {
      HttpServer httpServer = HttpServer.create(new InetSocketAddress("localhost", 0), 0);
      CurrentNonceServer server = new CurrentNonceServer(httpServer);
      httpServer.createContext("/", server::handle);
      httpServer.start();
      return server;
   }

   private static StaleNonceServer startStaleNonceServer() throws IOException {
      HttpServer httpServer = HttpServer.create(new InetSocketAddress("localhost", 0), 0);
      StaleNonceServer server = new StaleNonceServer(httpServer);
      httpServer.createContext("/", server::handle);
      httpServer.start();
      return server;
   }

   private static RestClient createClient(HttpServer httpServer) {
      String uri = "http://localhost:" + httpServer.getAddress().getPort();
      RestClientConfigurationBuilder restBuilder = new RestClientConfigurationBuilder();
      restBuilder.uri(uri).pingOnCreate(false);
      restBuilder.security().authentication()
            .mechanism("AUTO")
            .username(USERNAME)
            .password(PASSWORD);
      return new org.infinispan.client.rest.impl.jdk.RestClientJDK(restBuilder.build());
   }

   /**
    * A stateless server which issues a fresh nonce for every challenge and only accepts a digest response
    * computed against the currently valid nonce, so preauthenticated requests carrying a stale nonce are
    * rejected and must retry with the fresh challenge.
    */
   private static final class CurrentNonceServer {
      private final HttpServer httpServer;
      private final AtomicReference<String> currentNonce = new AtomicReference<>(newNonce());
      final List<String> acceptedCnonces = Collections.synchronizedList(new ArrayList<>());
      final List<String> acceptedNonces = Collections.synchronizedList(new ArrayList<>());
      final List<String> acceptedNcValues = Collections.synchronizedList(new ArrayList<>());

      CurrentNonceServer(HttpServer httpServer) {
         this.httpServer = httpServer;
      }

      void handle(HttpExchange exchange) throws IOException {
         String authorization = exchange.getRequestHeaders().getFirst("Authorization");
         try (exchange) {
            if (authorization != null && verifyDigest(authorization, currentNonce.get())) {
               Map<String, String> fields = parseDigestFields(authorization);
               synchronized (acceptedCnonces) {
                  acceptedCnonces.add(fields.get("cnonce"));
                  acceptedNonces.add(fields.get("nonce"));
                  acceptedNcValues.add(fields.get("nc"));
               }
               // Rotate the nonce like a server consuming it: preauthenticated requests carrying it must retry with a fresh challenge.
               currentNonce.set(newNonce());
               sendOk(exchange);
            } else {
               // Re-challenge with the current nonce (no rotation): like a real server, the nonce stays
               // valid across retries, so a client's digest computed against it is still fresh.
               sendChallenge(exchange, currentNonce.get(), false);
            }
         }
      }

      void stop() {
         httpServer.stop(0);
      }
   }

   /**
    * A server which re-challenges with the same nonce and {@code stale=true} after the first digest attempt,
    * mimicking a server whose nonce is still valid but whose first response was rejected for other reasons.
    */
   private static final class StaleNonceServer {
      private final HttpServer httpServer;
      private String nonce = newNonce();
      private boolean challengedOnce = false;
      final List<String> acceptedNcValues = Collections.synchronizedList(new ArrayList<>());

      StaleNonceServer(HttpServer httpServer) {
         this.httpServer = httpServer;
      }

      synchronized void handle(HttpExchange exchange) throws IOException {
         String authorization = exchange.getRequestHeaders().getFirst("Authorization");
         try (exchange) {
            if (authorization != null && verifyDigest(authorization, nonce)) {
               Map<String, String> fields = parseDigestFields(authorization);
               if ("00000002".equals(fields.get("nc"))) {
                  acceptedNcValues.add(fields.get("nc"));
                  sendOk(exchange);
                  return;
               }
            }
            sendChallenge(exchange, nonce, challengedOnce);
            challengedOnce = true;
         }
      }

      void stop() {
         httpServer.stop(0);
      }
   }

   private static void sendChallenge(HttpExchange exchange, String nonce, boolean stale) throws IOException {
      StringBuilder header = new StringBuilder("Digest realm=\"").append(REALM).append("\", nonce=").append(nonce).append(", qop=\"auth\"");
      if (stale) {
         header.append(", stale=\"true\"");
      }
      exchange.getResponseHeaders().add("WWW-Authenticate", header.toString());
      exchange.sendResponseHeaders(401, -1);
   }

   private static void sendOk(HttpExchange exchange) throws IOException {
      byte[] body = "ok".getBytes(StandardCharsets.UTF_8);
      exchange.getResponseHeaders().set("Content-Type", "text/plain");
      exchange.sendResponseHeaders(200, body.length);
      try (OutputStream os = exchange.getResponseBody()) {
         os.write(body);
      }
   }

   /**
    * Verifies a digest response computed with {@code qop=auth} and MD5, as the client does.
    */
   private static boolean verifyDigest(String authorization, String nonce) {
      Map<String, String> fields = parseDigestFields(authorization);
      if (!authorization.startsWith("Digest ") || !fields.containsKey("response") || !nonce.equals(fields.get("nonce"))) {
         return false;
      }
      String ha1 = md5Hex(fields.get("username") + ":" + fields.get("realm") + ":" + PASSWORD);
      String ha2 = md5Hex("GET:" + URI);
      String expected = md5Hex(ha1 + ":" + fields.get("nonce") + ":" + fields.get("nc") + ":" + fields.get("cnonce") + ":auth:" + ha2);
      return expected.equalsIgnoreCase(fields.get("response"));
   }

   private static Map<String, String> parseDigestFields(String authorization) {
      Map<String, String> fields = new HashMap<>();
      Matcher matcher = DIGEST_FIELD.matcher(authorization);
      while (matcher.find()) {
         fields.put(matcher.group(1), matcher.group(2) != null ? matcher.group(2) : matcher.group(3));
      }
      return fields;
   }

   private static String md5Hex(String data) {
      try {
         MessageDigest md = MessageDigest.getInstance("MD5");
         return Util.toHexString(md.digest(data.getBytes(StandardCharsets.UTF_8))).toLowerCase();
      } catch (NoSuchAlgorithmException e) {
         throw new IllegalStateException(e);
      }
   }

   private static String newNonce() {
      byte[] tmp = new byte[8];
      new SecureRandom().nextBytes(tmp);
      return Util.toHexString(tmp);
   }
}
